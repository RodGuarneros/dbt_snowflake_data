SELECT 
    CAST(DDATE AS DATE) AS DDATE,
    SALESPERSON,
    CUSTOMENAME,
    CARMAKE,
    CARMODEL,
    CAST(CARYEAR AS NUMBER) AS CARYEAR,
    SALEPRICE,
    COMMISSIONRATE AS COMRATE,
    COMMISSIONEARNED AS COMEA
FROM {{source('raw_bi_car','AUTOS')}}
WHERE CAST(DDATE AS DATE) > '2018-01-01'
